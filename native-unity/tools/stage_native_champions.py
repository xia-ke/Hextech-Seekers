#!/usr/bin/env python3
"""Stage verified *local* champion assets into Unity without downloading or committing art.

Input directories are generated by import_native_hero.py under a persistent
external root (one directory per original hero). This script does not fetch,
redistribute, invent or claim to verify visual similarity to Riot artwork.
GitHub Actions clean the checkout before staging, so the external root must
remain outside the Git workspace.
"""
import argparse
import hashlib
import json
import os
import re
import shutil
import tempfile
from pathlib import Path

NATIVE = Path(__file__).resolve().parents[1]
DEFAULT_TARGET = NATIVE / "Assets" / "StreamingAssets" / "Champions"
HEROES = ("Blitzcrank", "Riven", "Yasuo")
HASH_RE = re.compile(r"^[0-9a-f]{64}$")
MAX_FILE_BYTES = 64 * 1024 * 1024


def digest(path: Path) -> str:
    h = hashlib.sha256()
    with path.open("rb") as stream:
        for block in iter(lambda: stream.read(1024 * 1024), b""):
            h.update(block)
    return h.hexdigest()


def regular_file(folder: Path, name: str) -> Path:
    if not name or name != Path(name).name or name in (".", "..") or "\\" in name or "/" in name:
        raise ValueError("Unsafe file name in source manifest: " + repr(name))
    path = folder / name
    if path.is_symlink() or not path.is_file():
        raise ValueError("Original champion file missing or linked: " + name)
    size = path.stat().st_size
    if size == 0 or size > MAX_FILE_BYTES:
        raise ValueError("Invalid original champion file size: " + name)
    return path


def validate_bundle(folder: Path, hero: str) -> dict:
    """Validate source provenance and exactly the files Unity will consume."""
    if hero not in HEROES or folder.is_symlink() or not folder.is_dir():
        raise ValueError("Expected an unlinked imported champion folder")
    name = hero.lower()
    manifest_file = regular_file(folder, name + ".json")
    provenance_file = regular_file(folder, "local-import-provenance.json")
    manifest = json.loads(manifest_file.read_text(encoding="utf-8"))
    proof = json.loads(provenance_file.read_text(encoding="utf-8"))
    if not isinstance(manifest, dict) or manifest.get("version") != 1 or manifest.get("hero") != hero:
        raise ValueError("Original mesh manifest hero/version mismatch: " + hero)
    if not isinstance(proof, dict) or proof.get("hero") != hero or proof.get("status") != "SOURCE_PREPARED_NOT_VISUALLY_VALIDATED":
        raise ValueError("Original source import provenance is missing: " + hero)
    source_proof = manifest.get("provenance")
    if not isinstance(source_proof, dict) or not all(
        isinstance(source_proof.get(key), str) and HASH_RE.fullmatch(source_proof[key])
        for key in ("meshSHA256", "animationSHA256")
    ):
        raise ValueError("Original source SHA256 is missing: " + hero)
    if (proof.get("sourceMeshSha256") != source_proof["meshSHA256"] or
            proof.get("sourceAnimationSha256") != source_proof["animationSHA256"]):
        raise ValueError("Original source hashes disagree with import audit: " + hero)

    texture = manifest.get("texture")
    binary = manifest.get("binary")
    if not isinstance(texture, str) or not texture.lower().endswith(".png") or binary != name + ".bin":
        raise ValueError("Unsafe or mismatched Unity champion texture/binary: " + hero)
    clips = manifest.get("clips")
    if not isinstance(clips, list):
        raise ValueError("Missing original animation clips: " + hero)
    clip_names = [clip.get("name") for clip in clips if isinstance(clip, dict)]
    if len(clip_names) != len(clips) or not (
        {"idle", "run"} <= set(clip_names) or {"idle1", "run"} <= set(clip_names)
    ) or "attack1" not in clip_names:
        raise ValueError("Original idle, run and basic attack clips are required: " + hero)
    if not isinstance(manifest.get("bones"), list) or not manifest["bones"]:
        raise ValueError("Original skeleton missing: " + hero)
    if not isinstance(manifest.get("geometry"), dict) or not manifest["geometry"]:
        raise ValueError("Original geometry missing: " + hero)

    files = [name + ".json", binary, texture]
    bindings_file = folder / "animation-bindings.json"
    has_bindings = bindings_file.is_file()
    if bindings_file.is_symlink():
        raise ValueError("Unsafe linked original animation bindings")
    if has_bindings:
        binding = json.loads(regular_file(folder, "animation-bindings.json").read_text(encoding="utf-8"))
        if not isinstance(binding, dict) or binding.get("hero") != hero or binding.get("version") != 1 or binding.get("sourceVerified") is not True:
            raise ValueError("Skill binding needs verified source and matching hero: " + hero)
        mapped = [binding.get(key) for key in ("q1", "q2", "q3", "w", "e") if binding.get(key)]
        if not mapped or any(not isinstance(clip, str) or clip not in clip_names for clip in mapped):
            raise ValueError("Skill binding refers to a missing original clip: " + hero)
        files.append("animation-bindings.json")
    if proof.get("verifiedAbilityBindings") is not has_bindings:
        raise ValueError("Skill binding state differs from import provenance: " + hero)

    hashes = proof.get("bundleSha256")
    if not isinstance(hashes, dict) or set(hashes) != set(files):
        raise ValueError("Reimport this hero with a SHA256 bundle manifest: " + hero)
    for name in files:
        file = regular_file(folder, name)
        if not isinstance(hashes[name], str) or not HASH_RE.fullmatch(hashes[name]) or digest(file) != hashes[name]:
            raise ValueError("Imported Unity source SHA256 mismatch: " + hero + "/" + name)
    if regular_file(folder, texture).open("rb").read(8) != b"\x89PNG\r\n\x1a\n":
        raise ValueError("Original source texture does not contain PNG bytes: " + hero)

    return {"hero": hero, "clips": clip_names, "files": files,
            "verifiedAbilityBindings": has_bindings}


def install_one(source_folder: Path, target_root: Path, hero: str) -> dict:
    report = validate_bundle(source_folder, hero)
    target_root.mkdir(parents=True, exist_ok=True)
    if target_root.is_symlink():
        raise ValueError("Unity target root must not be a symlink")
    # Staging on the same filesystem allows the final rename to be atomic.
    with tempfile.TemporaryDirectory(prefix="hextech-hero-", dir=target_root) as staging_dir:
        staged = Path(staging_dir) / hero
        staged.mkdir()
        for name in report["files"]:
            shutil.copyfile(source_folder / name, staged / name)
        shutil.copyfile(source_folder / "local-import-provenance.json",
                        staged / "local-import-provenance.json")
        copied = validate_bundle(staged, hero)
        destination = target_root / hero
        backup = Path(staging_dir) / "previous"
        if destination.is_symlink():
            raise ValueError("Unity destination must not be a symlink")
        if destination.exists():
            if not destination.is_dir():
                raise ValueError("Unity destination must be a directory")
            destination.rename(backup)
        try:
            staged.rename(destination)
        except Exception:
            if backup.exists() and not destination.exists():
                backup.rename(destination)
            raise
        return copied


def stage_available(source_root: Path, target_root: Path, required=()) -> list:
    required = tuple(required)
    if any(hero not in HEROES for hero in required):
        raise ValueError("Unsupported required champion")
    if not source_root.is_dir() or source_root.is_symlink():
        if required:
            raise FileNotFoundError("Required external champion source root is unavailable")
        return []
    # Pre-validate all available heroes before modifying the Unity target.
    present = []
    for hero in HEROES:
        folder = source_root / hero
        if not folder.exists():
            if hero in required:
                raise FileNotFoundError("Required original champion is absent: " + hero)
            continue
        validate_bundle(folder, hero)
        present.append(hero)
    return [install_one(source_root / hero, target_root, hero) for hero in present]


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--source-root", type=Path, required=True)
    parser.add_argument("--target-root", type=Path, default=DEFAULT_TARGET)
    parser.add_argument("--require", action="append", default=[], choices=HEROES,
                        help="Fail if this champion's original source is not available")
    args = parser.parse_args()
    reports = stage_available(args.source_root, args.target_root, args.require)
    if not reports:
        print("NATIVE_CHAMPION_SOURCE_NOT_CONFIGURED: using existing Garen baseline only")
    for report in reports:
        print("NATIVE_ORIGINAL_HERO_STAGED: " + report["hero"] +
              " clips=" + str(len(report["clips"])) +
              " skillBindings=" + str(report["verifiedAbilityBindings"]))
    print("NATIVE_OPTIONAL_HERO_STAGING_COMPLETE: count=" + str(len(reports)))


if __name__ == "__main__":
    main()
